describe("GRW-P4-B1 link code (copy parity with the Clinic)", () => {
  it("reproduces every vector generated by the Clinic code", () => {
    const v = JSON.parse(readFileSync(join(__dirname, "fixtures", "link-code-vectors.json"), "utf8")) as { vectors: Array<{ seedHex: string; code: string }> };
    assert.ok(v.vectors.length >= 12);
    for (const r of v.vectors) assert.equal(generateLinkCode(() => Buffer.from(r.seedHex, "hex")), r.code);
  });
  it("is 8 Crockford characters without I L O U, uniform and collision free", () => {
    assert.equal(LINK_CODE_ALPHABET.length, 32);
    for (const bad of "ILOU") assert.ok(!LINK_CODE_ALPHABET.includes(bad));
    const seen = new Set<string>(); const counts = new Map<string, number>(); const N = 30_000;
    for (let i = 0; i < N; i += 1) { const c = generateLinkCode(); assert.match(c, LINK_CODE_PATTERN); seen.add(c); for (const ch of c) counts.set(ch, (counts.get(ch) ?? 0) + 1); }
    assert.equal(seen.size, N);
    const expected = (N * 8) / 32;
    for (const ch of LINK_CODE_ALPHABET) assert.ok(Math.abs((counts.get(ch) ?? 0) - expected) < expected * 0.08, ch);
  });
  it("normalises case and rejects malformed input", () => {
    assert.equal(normalizeLinkCode(" 7k3m9qxa "), "7K3M9QXA");
    for (const bad of ["", "7K3M9QX", "7K3M9QXAA", "7K3M9QXI", "7K3M9QXO", "7K3M9QXL", "7K3M9QXU", "../etc/pw", "https://evil.test", null, undefined, 42]) assert.equal(normalizeLinkCode(bad), null);
  });
});

describe("GRW-P4-B1 signed link touch (lt)", () => {
  const secret = "test-secret"; const now = new Date("2026-11-24T10:00:00Z");
  it("round-trips and carries only org, code and time", () => {
    const t = signLinkTouch({ orgId: "org1", code: "7K3M9QXA", now }, secret)!;
    const v = verifyLinkTouch(t, { now, secret });
    assert.ok(v.ok);
    if (v.ok) assert.deepEqual(Object.keys(v.claims).sort(), ["c", "o", "t", "v"]);
    assert.ok(!/[+/=]/.test(t));
  });
  it("is byte-identical to the Clinic token for the same inputs (Kiorex verifies one format)", () => {
    const t = signLinkTouch({ orgId: "org1", code: "7K3M9QXA", now }, secret)!;
    assert.equal(t, "eyJvIjoib3JnMSIsImMiOiI3SzNNOVFYQSIsInQiOjE3OTU1MTQ0MDAwMDAsInYiOjF9.Sh98JqND49syYon0dVDPnRiJUd6swxQZWs1o_YH7wSs", "token produced by the Clinic link-touch.ts for the same inputs");
  });
  it("rejects tampering, a wrong secret, expiry, a future token and garbage", () => {
    const t = signLinkTouch({ orgId: "org1", code: "7K3M9QXA", now }, secret)!;
    const [p, s] = t.split(".");
    const forged = Buffer.from(JSON.stringify({ o: "org2", c: "7K3M9QXA", t: now.getTime(), v: 1 })).toString("base64url");
    assert.deepEqual(verifyLinkTouch(`${forged}.${s}`, { now, secret }), { ok: false, reason: "BAD_SIGNATURE" });
    assert.deepEqual(verifyLinkTouch(t, { now, secret: "other" }), { ok: false, reason: "BAD_SIGNATURE" });
    assert.deepEqual(verifyLinkTouch(`${p}`, { now, secret }), { ok: false, reason: "MALFORMED" });
    assert.deepEqual(verifyLinkTouch("x".repeat(700), { now, secret }), { ok: false, reason: "MALFORMED" });
    assert.deepEqual(verifyLinkTouch(t, { now: new Date(now.getTime() + LINK_TOUCH_DEFAULT_TTL_MS + 1), secret }), { ok: false, reason: "EXPIRED" });
    assert.deepEqual(verifyLinkTouch(t, { now: new Date(now.getTime() - 3_600_000), secret }), { ok: false, reason: "EXPIRED" });
    assert.equal(signLinkTouch({ orgId: "o", code: "bad" }, secret), null);
  });
});

describe("GRW-P4-B1 redirect safety (open redirect)", () => {
  it("builds the destination from configuration only and always on the configured Kiorex host", () => {
    const lt = signLinkTouch({ orgId: "o1", code: "7K3M9QXA" }, "s")!;
    const u = new URL(kiorexLandingUrl({ product: "PHARMACY", lt, channelKind: "QR_DESK" }, ENV));
    assert.equal(u.origin, "https://kiorex.test"); assert.equal(u.pathname, "/pharmacy"); assert.equal(u.searchParams.get("lt"), lt);
    assert.equal(u.searchParams.get("utm_medium"), "qr");
    assert.equal(new URL(kiorexLandingUrl({ product: "LAB" }, ENV)).pathname, "/lab");
    assert.equal(new URL(kiorexLandingUrl({ product: "PHARMACY" }, ENV)).search, "", "no lt, no tags: plain page");
  });
  it("assertAllowedRedirect refuses other hosts, userinfo tricks, schemes and plain http", () => {
    assert.ok(assertAllowedRedirect("https://kiorex.test/pharmacy?lt=x", ENV));
    for (const bad of ["https://evil.test/pharmacy", "https://kiorex.test.evil.test/", "https://kiorex.test@evil.test/", "https://user:pw@kiorex.test/", "http://kiorex.test/", "javascript:alert(1)", "//evil.test", "data:text/html,x", "", "not a url", "https://kiorex.test:8443/"]) assert.throws(() => assertAllowedRedirect(bad, ENV), /REDIRECT_NOT_ALLOWED/, bad);
    assert.ok(assertAllowedRedirect("http://localhost:5180/pharmacy", { ...ENV, KIOREX_PATIENT_WEB_URL: "http://localhost:5180" } as NodeJS.ProcessEnv));
    assert.deepEqual([...allowedRedirectHosts({ ...ENV, KIOREX_ALLOWED_REDIRECT_HOSTS: "a.test, https://b.test" } as NodeJS.ProcessEnv)].sort(), ["a.test", "b.test", "kiorex.test"]);
  });
  it("short links are the API resolver URL until kiorly.link is configured", () => {
    assert.equal(shortUrl("7K3M9QXA", ENV), "https://api.pharmacy.test/api/v1/public/links/q/7K3M9QXA");
    assert.equal(shortUrl("7K3M9QXA", { ...ENV, LINK_SHORT_BASE_URL: "https://kiorly.link/" } as NodeJS.ProcessEnv), "https://kiorly.link/q/7K3M9QXA");
  });
});

describe("GRW-P4-B1 tags and bots", () => {
  it("tags are short tokens only", () => {
    assert.deepEqual(sanitizeLinkTags({ utm_campaign: " Spring-26 " }), { ok: true, tags: { utm_campaign: "spring-26" } });
    for (const bad of [{ utm_campaign: "<script>" }, { x: "y" }, { utm_source: "a b" }, { utm_source: 5 }, []]) assert.equal(sanitizeLinkTags(bad as never).ok, false);
    assert.equal(effectiveTags("QR_DESK", null).utm_medium, "qr");
  });
  it("crawlers, previews and prefetch are not visits; a browser is", () => {
    const ua = "Mozilla/5.0 (iPhone; CPU iPhone OS 17_0 like Mac OS X) AppleWebKit/605.1.15 Safari/604.1";
    assert.equal(isLikelyBot({ "user-agent": ua }), false);
    assert.equal(isLikelyBot({}), true); assert.equal(isLikelyBot({ "user-agent": "curl/8" }), true);
    assert.equal(isLikelyBot({ "user-agent": "Slackbot-LinkExpanding 1.0" }), true);
    assert.equal(isLikelyBot({ "user-agent": ua, purpose: "prefetch" }), true);
  });
});

describe("GRW-P4-B1 QR and printable cards", () => {
  const url = "https://kiorly.link/q/7K3M9QXA";
  it("SVG equals the Clinic golden snapshot (copy parity), error correction M, 4 module quiet zone", async () => {
    assert.equal(await qrSvg(url), readFileSync(join(__dirname, "fixtures", "qr-golden.svg"), "utf8"));
    const modules = QRCode.create(url, { errorCorrectionLevel: "M" }).modules.size;
    assert.match(await qrSvg(url), new RegExp(`viewBox="0 0 ${modules + 8} ${modules + 8}"`));
  });
  it("PNG is a PNG of the requested width (clamped)", async () => {
    const png = await qrPng(url, 512);
    assert.equal(png.subarray(1, 4).toString(), "PNG"); assert.equal(png.readUInt32BE(16), 512);
    assert.equal((await qrPng(url, 99999)).readUInt32BE(16), 2048);
  });
  it("poster: Arabic is RTL, English is LTR, A4 and A5 differ, output is escaped, no script unless print is requested", async () => {
    const base = { product: "PHARMACY" as const, kind: "POSTER" as const, size: "A4" as const, nameEn: "Nile <b>Pharmacy</b>", nameAr: "صيدلية النيل", shortUrl: url, qrSvg: await qrSvg(url) };
    const ar = renderPosterHtml({ ...base, lang: "ar" }); const en = renderPosterHtml({ ...base, lang: "en" });
    assert.match(ar, /<html lang="ar" dir="rtl">/); assert.match(en, /<html lang="en" dir="ltr">/);
    assert.ok(ar.includes("صيدلية النيل")); assert.ok(en.includes("Nile &lt;b&gt;Pharmacy&lt;/b&gt;")); assert.ok(!en.includes("<b>Pharmacy"));
    assert.ok(!/<script/.test(en)); assert.ok(/<script>window\.addEventListener/.test(renderPosterHtml({ ...base, lang: "en", autoPrint: true })));
    assert.notEqual(renderPosterHtml({ ...base, lang: "en", size: "A5" }), en);
    assert.match(renderPosterHtml({ ...base, lang: "en", kind: "DESK", subtitleEn: "Counter 2" }), /Counter 2/);
    assert.match(en, /Kiorly Pharmacy by Kiorex/); assert.match(renderPosterHtml({ ...base, product: "LAB", lang: "ar" }), /كيورلي لاب/);
  });
});

describe("GRW-P4-B1 roles, plans, recommendations, performance", () => {
  const ROLES: StaffRole[] = ["OWNER", "PHARMACIST", "CASHIER", "ASSISTANT", "BRANCH_MANAGER", "CHAIN_OPS"];
  it("owner and manager manage; every other staff role reads; nobody has a doctor scope", () => {
    assert.deepEqual(ROLES.filter((r) => canGrowth(r, "create")).sort(), ["BRANCH_MANAGER", "OWNER"]);
    assert.deepEqual(ROLES.filter((r) => canGrowth(r, "revoke")).sort(), ["BRANCH_MANAGER", "OWNER"]);
    for (const r of ROLES) assert.ok(canGrowth(r, "view"), r);
    assert.equal(growthLevel("CASHIER"), "read");
  });
  it("plan limits mirror the Clinic and fall back to LITE", () => {
    assert.deepEqual(Object.fromEntries(Object.entries(GROWTH_PLAN_LIMITS).map(([k, v]) => [k, v.maxActiveLinks])), { LITE: 3, PRO: 25, CHAIN: 100, ENTERPRISE: 500 });
    assert.equal(growthLimitsFor("???").maxActiveLinks, 3);
  });
  const base = { activeLinks: 2, hasDeskLink: true, branchesNotListed: 0, unusedLinks: 0, kiorexOrders30d: 0, rejectedOrCancelled30d: 0 };
  it("closed catalogue of five rules, ordered by severity", () => {
    assert.equal(RECOMMENDATION_IDS.length, 5);
    assert.deepEqual(buildRecommendations(base), []);
    assert.deepEqual(buildRecommendations({ ...base, activeLinks: 0, hasDeskLink: false }).map((r) => r.id), ["CREATE_FIRST_LINK"]);
    const all = buildRecommendations({ ...base, hasDeskLink: false, branchesNotListed: 2, unusedLinks: 1, kiorexOrders30d: 10, rejectedOrCancelled30d: 3 });
    assert.deepEqual(all.map((r) => r.id), ["BRANCH_NOT_LISTED", "HIGH_REJECTION", "PRINT_COUNTER_CARD", "LINKS_UNUSED"]);
    assert.equal(all[1]!.params.percent, 30);
    assert.equal(buildRecommendations({ ...base, kiorexOrders30d: 7, rejectedOrCancelled30d: 7 }).length, 0, "rates need at least 8 orders");
    for (const r of all) assert.ok(RECOMMENDATION_IDS.includes(r.id));
  });
  it("performance is counts only, never money, and shows everything as marketplace until the acquisition block arrives", () => {
    const p = buildPerformance({ total: 10, completed: 6, rejectedOrCancelled: 2 }, { visits: 40, orders: 0, completed: 0 });
    assert.equal(p.acquisitionPending, true); assert.equal(p.marketplaceOriginated.orders, 10); assert.equal(p.providerOriginated.orders, 0);
    const q = buildPerformance({ total: 10, completed: 6, rejectedOrCancelled: 2 }, { visits: 40, orders: 4, completed: 3 });
    assert.equal(q.providerOriginated.orders, 4); assert.equal(q.marketplaceOriginated.orders, 6); assert.equal(q.marketplaceOriginated.completed, 3);
    assert.equal(q.links.visitToOrder, 0.1);
    assert.doesNotMatch(JSON.stringify(Object.keys(q)) + JSON.stringify(Object.keys(q.links)), /value|price|amount|fee|money|commission/i);
  });
});

describe("GRW-P4-B1 registry events validate against @kiorex/contracts 1.12.0 and carry the product", () => {
  const link = { code: "7K3M9QXA", orgId: "org_1", branchRef: "br_1", ownerScope: "DESK", channelKind: "QR_DESK", createdAt: new Date("2026-11-24T10:00:00Z"), revokedAt: new Date("2026-11-25T10:00:00Z"), status: "REVOKED", updatedAt: new Date() } as never;
  const env = (type: string, data: unknown) => ({ eventId: "e1", type, aggregateType: "ProviderReferralLink", aggregateId: "l1", target: "KIOREX", occurredAt: new Date().toISOString(), data });
  it("created and revoked pass the contract schemas and carry product PHARMACY", () => {
    const c = linkEventData(REFERRAL_LINK_CREATED, link); const r = linkEventData(REFERRAL_LINK_REVOKED, link, "PROVIDER_REQUEST");
    assert.equal(c.product, "PHARMACY"); assert.equal(r.product, "PHARMACY"); assert.equal(c.orgRef, "org_1");
    assert.equal(validateEvent(REFERRAL_LINK_CREATED, env(REFERRAL_LINK_CREATED, c)).valid, true);
    assert.equal(validateEvent(REFERRAL_LINK_REVOKED, env(REFERRAL_LINK_REVOKED, r)).valid, true);
    assert.equal(validateEvent(REFERRAL_LINK_CREATED, env(REFERRAL_LINK_CREATED, { ...c, product: "BOGUS" })).valid, false, "the validator really checks the product enum");
  });
  it("payloads and the lookup record carry no person and no order", () => {
    const s = JSON.stringify([linkEventData(REFERRAL_LINK_CREATED, link), linkEventData(REFERRAL_LINK_REVOKED, link), toReferralLinkRecord(link)]);
    assert.doesNotMatch(s, /customer|patient|phone|email|order|price/i);
    assert.equal(toReferralLinkRecord(link).product, "PHARMACY");
  });
});

